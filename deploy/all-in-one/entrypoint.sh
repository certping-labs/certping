# config.env is generated below; its keys are read by sourcing it in subshells.
# shellcheck disable=SC1090,SC2153
# CertPing all-in-one entrypoint. Runs as root once per start: prepares the data volume, writes
# the installation's secrets on the first start, initializes PostgreSQL on the first start, writes
# one environment file per service with only the values that service needs, then hands over to
# supervisord, which runs every service as an unprivileged user:
#   certping (185)           server and bundled agent (they share the encrypted secrets volume)
#   certping-notifier (186)  notifier
#   certping-web (187)       web app
#   certping-caddy (188)     Caddy (TLS certificates in caddy/)
#   valkey, postgres         Valkey (Redis compatible) and PostgreSQL
# config.env, the full set of secrets, stays readable by root only (certping-admin reads it).
set -euo pipefail

data=/var/lib/certping
config="$data/config.env"
run=/run/certping
pgdata="$data/postgres"
pgbin=/usr/lib/postgresql/current/bin

log() { printf '%s certping-entrypoint: %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$*"; }

url="${CERTPING_URL:-http://localhost}"
url="${url%/}"
case "$url" in
  http://localhost|http://localhost:*|http://127.0.0.1|http://127.0.0.1:*) site=":80" ;;
  https://*) site="${url#https://}" ;;
  http://*)  site="http://${url#http://}" ;;
  *) echo "CERTPING_URL must start with http:// or https:// (got '$url')" >&2; exit 2 ;;
esac

admin_domain="${url#*://}"; admin_domain="${admin_domain%%/*}"; admin_domain="${admin_domain%%:*}"
[[ "$admin_domain" == "localhost" || "$admin_domain" == "127.0.0.1" ]] && admin_domain="certping.local"
first_start=0

# Earlier images ran Redis 8 with its data in redis/. Valkey replaced it and cannot read the
# RDB format 12 that Redis 8 writes. The store holds only short-lived state (revoked access tokens,
# rate-limit counters, the feature flag version), so Valkey starts empty and the old files are
# kept aside, readable by root only, for whoever wants to delete them.
if [[ -d "$data/redis" && ! -e "$data/valkey" ]]; then
  if [[ -n "$(ls -A "$data/redis")" ]]; then
    mv "$data/redis" "$data/redis.pre-valkey"
    chown -R root:root "$data/redis.pre-valkey"
    chmod 0700 "$data/redis.pre-valkey"
    log "Valkey replaced Redis: starting with an empty cache (revoked tokens, rate limits);" \
      "the old Redis files are in $data/redis.pre-valkey and can be deleted"
  else
    rmdir "$data/redis"
  fi
fi

mkdir -p "$data/secrets" "$data/valkey" "$data/caddy" /var/run/postgresql /var/log/certping \
  /var/cache/certping-web "$run"
chown certping:certping "$data" "$data/secrets" /var/log/certping
chmod 0770 "$data/secrets"
# Earlier images ran the store and Caddy as certping; each now has its own account.
chown -R valkey:valkey "$data/valkey"
chmod 0700 "$data/valkey"
chown -R certping-caddy:certping-caddy "$data/caddy"
chmod 0700 "$data/caddy"
chown certping-web:certping-web /var/cache/certping-web
chmod 0700 /var/cache/certping-web
chown postgres:postgres /var/run/postgresql
chown root:root "$run"
chmod 0711 "$run"

rand()  { openssl rand -base64 "$1" | tr -d '\n'; }
token() { openssl rand -base64 64 | tr -dc 'A-Za-z0-9' | head -c "$1"; }

if [[ ! -f "$config" ]]; then
  log "first start: writing $config with fresh secrets (back this file up with the volume)"
  umask 077
  {
    echo "# Generated by the CertPing all-in-one image on $(date -u +%Y-%m-%dT%H:%M:%SZ)."
    echo "# Every value here protects the database, the password hashes or the stored private keys."
    echo "# Keep it with the volume; a copy of the database without it cannot be restored."
    echo "DB_USERNAME='certping'"
    echo "DB_PASSWORD='$(token 32)'"
    echo "REDIS_PASSWORD='$(token 40)'"
    echo "PASSWORD_PEPPER_ACTIVE_VERSION='v1'"
    echo "PASSWORD_PEPPER_V1='$(rand 32)'"
    echo "PASSWORD_RESET_TOKEN_SECRET='$(token 48)'"
    echo "CERTPING_INTERNAL_TOKEN='$(token 48)'"
    echo "CERTPING_BOOTSTRAP_AGENT_TOKEN='cpa_$(token 43)'"
    echo "CERTPING_BOOTSTRAP_AGENT_ORG=''"
    echo "CERTPING_LOCAL_SECRET_KEY='$(rand 32)'"
    # The first Platform Super Admin, created by the server at its first start. The password is
    # random per installation and must be changed at the first sign-in.
    # Values given to the container win over the generated ones.
    echo "BOOTSTRAP_SUPER_ADMIN_USERNAME='${BOOTSTRAP_SUPER_ADMIN_USERNAME:-admin}'"
    echo "BOOTSTRAP_SUPER_ADMIN_EMAIL='${BOOTSTRAP_SUPER_ADMIN_EMAIL:-admin@${admin_domain}}'"
    echo "BOOTSTRAP_SUPER_ADMIN_PASSWORD='${BOOTSTRAP_SUPER_ADMIN_PASSWORD:-$(token 20)-9aA}'"
    echo "BOOTSTRAP_SUPER_ADMIN_DISPLAY_NAME='${BOOTSTRAP_SUPER_ADMIN_DISPLAY_NAME:-Administrator}'"
    /usr/local/bin/certping-jwt-keygen "allinone-$(date +%Y%m%d)" "$url"
  } > "$config"
  first_start=1
fi

# Volumes from before the store had a password: add one.
if ! grep -q '^REDIS_PASSWORD=' "$config"; then
  echo "REDIS_PASSWORD='$(token 40)'" >> "$config"
fi

# The public URL comes from the container's environment on every start, so it can change.
grep -v '^CERTPING_URL=\|^CERTPING_SITE_ADDRESS=\|^JWT_ISSUER=' "$config" > "$config.next"
{
  echo "CERTPING_URL='$url'"
  echo "CERTPING_SITE_ADDRESS='$site'"
  echo "JWT_ISSUER='$url'"
} >> "$config.next"
mv "$config.next" "$config"
chown root:root "$config"
chmod 0600 "$config"

# One environment file per service, 0600 and owned by the account that runs it, holding only the
# values it needs. Web and Caddy get no secrets at all.
write_env() {
  local file="$run/$1" owner="$2"; shift 2
  (
    umask 077
    set -a; . "$config"; set +a
    for key in "$@"; do printf '%s=%q\n' "$key" "${!key-}"; done
  ) > "$file.next"
  chown "$owner:$owner" "$file.next"
  chmod 0600 "$file.next"
  mv "$file.next" "$file"
}
# The server needs nearly every key (database, Valkey, pepper, JWT, tokens, secret store).
mapfile -t all_keys < <(grep -oE '^[A-Z0-9_]+=' "$config" | tr -d '=' | grep -v '^CERTPING_SITE_ADDRESS$')
write_env server.env   certping          "${all_keys[@]}"
# The release this image is (ENV CERTPING_VERSION from the build); the server shows it as the
# agent image tag in the "Add agent" command. Written on every start, so an upgrade updates it.
printf 'CERTPING_VERSION=%q\n' "${CERTPING_VERSION:-}" >> "$run/server.env"
write_env agent.env    certping          CERTPING_URL CERTPING_BOOTSTRAP_AGENT_TOKEN CERTPING_LOCAL_SECRET_KEY
write_env notifier.env certping-notifier CERTPING_URL DB_USERNAME DB_PASSWORD CERTPING_INTERNAL_TOKEN BOOTSTRAP_SUPER_ADMIN_EMAIL
write_env web.env      certping-web      CERTPING_URL
write_env caddy.env    certping-caddy    CERTPING_SITE_ADDRESS

# Valkey (the Redis-compatible store; the server still calls it Redis, hence REDIS_PASSWORD) reads
# its password from a config file only its account can open.
redis_password="$(. "$config"; printf '%s' "$REDIS_PASSWORD")"
(
  umask 077
  cat > "$run/valkey.conf.next" <<VALKEY
bind 127.0.0.1
port 6379
dir $data/valkey
save 60 1
appendonly yes
requirepass "$redis_password"
VALKEY
)
chown valkey:valkey "$run/valkey.conf.next"
mv "$run/valkey.conf.next" "$run/valkey.conf"
unset redis_password

db_password="$(. "$config"; printf '%s' "$DB_PASSWORD")"

if [[ ! -s "$pgdata/PG_VERSION" ]]; then
  log "first start: initializing PostgreSQL in $pgdata"
  mkdir -p "$pgdata"
  chown postgres:postgres "$pgdata"
  chmod 0700 "$pgdata"
  gosu postgres "$pgbin/initdb" -D "$pgdata" --encoding=UTF8 --locale=C.UTF-8 \
    --auth-local=peer --auth-host=scram-sha-256 >/dev/null
  gosu postgres "$pgbin/pg_ctl" -D "$pgdata" -w -o "-c listen_addresses=127.0.0.1 -c unix_socket_directories=/var/run/postgresql" start >/dev/null
  gosu postgres psql -v ON_ERROR_STOP=1 -v pw="$db_password" >/dev/null <<'SQL'
CREATE ROLE certping LOGIN PASSWORD :'pw';
CREATE DATABASE certping OWNER certping;
SQL
  gosu postgres "$pgbin/pg_ctl" -D "$pgdata" -w stop >/dev/null
  log "PostgreSQL initialized"
else
  chown -R postgres:postgres "$pgdata"
fi

if [[ "$first_start" == 1 ]]; then
  # The password is never written to the log; certping-admin shows it to whoever can exec in.
  admin_user="$(. "$config"; printf '%s' "$BOOTSTRAP_SUPER_ADMIN_USERNAME")"
  cat <<BANNER

==================================================================
 CertPing is starting for the first time.

   Open:      $url
   Username:  $admin_user
   Password:  docker exec certping certping-admin
              (use your container's name if it is not "certping")

 You will be asked to choose a new password at the first sign-in.
==================================================================

BANNER
fi

log "starting CertPing at $url (data in $data)"
# Extra CA certificates to trust (a private ACME CA such as step-ca, or a TLS-inspecting proxy):
# CERTPING_EXTRA_CA_CERTS points at a PEM file with one or more certificates. They are added to a
# copy of the Java trust store that every CertPing service then uses.
if [[ -n "${CERTPING_EXTRA_CA_CERTS:-}" ]]; then
  if [[ ! -r "$CERTPING_EXTRA_CA_CERTS" ]]; then
    echo "CERTPING_EXTRA_CA_CERTS=$CERTPING_EXTRA_CA_CERTS is not a readable file" >&2; exit 2
  fi
  store="$data/truststore.p12"
  java_home="$(dirname "$(dirname "$(readlink -f "$(command -v java)")")")"
  cp "$java_home/lib/security/cacerts" "$store"
  split_dir="$(mktemp -d)"
  awk -v dir="$split_dir" '/-----BEGIN CERTIFICATE-----/{n++} n{print > (dir "/ca-" n ".pem")}' "$CERTPING_EXTRA_CA_CERTS"
  count=0
  for pem in "$split_dir"/ca-*.pem; do
    [[ -e "$pem" ]] || continue
    count=$((count + 1))
    keytool -importcert -noprompt -alias "certping-extra-$count" -file "$pem" \
      -keystore "$store" -storepass changeit >/dev/null
  done
  rm -rf "$split_dir"
  chmod 0644 "$store"
  export JAVA_TOOL_OPTIONS="${JAVA_TOOL_OPTIONS:-} -Djavax.net.ssl.trustStore=$store -Djavax.net.ssl.trustStorePassword=changeit"
  log "trusting $count extra CA certificate(s) from $CERTPING_EXTRA_CA_CERTS"
fi

exec /usr/bin/supervisord -c /etc/certping/supervisord.conf
