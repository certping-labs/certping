# Writes .env for the CertPing Compose install, with fresh random secrets.
#
#   ./setup.sh                          # laptop quickstart, http://localhost
#   ./setup.sh certping.example.com     # a server with that DNS name, HTTPS via Let's Encrypt
#   ./setup.sh --upgrade                # adds keys that newer releases need to an existing .env
#
# Run it once. It refuses to overwrite an existing .env, because the database password and the
# encryption keys in it must stay the same for the life of the install. Keep a copy somewhere safe.
# --upgrade never changes or removes a key that is already there; it only appends missing ones.
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
# CERTPING_ENV_FILE writes somewhere else; the Helm chart's create-secret.sh uses it.
out="${CERTPING_ENV_FILE:-$here/.env}"

command -v openssl >/dev/null || { echo "openssl is required" >&2; exit 1; }

rand() { openssl rand -base64 "$1" | tr -d '\n'; }
# Alphanumeric only: these values end up in URLs, shell lines and YAML.
token() { openssl rand -base64 64 | tr -dc 'A-Za-z0-9' | head -c "$1"; }

if [[ "${1:-}" == "--upgrade" ]]; then
  if [[ ! -f "$out" ]]; then
    echo "$out does not exist; run ./setup.sh [domain] to create it" >&2
    exit 1
  fi
  added=()
  add_key() {
    if ! grep -q "^$1=" "$out"; then
      printf "%s='%s'\n" "$1" "$2" >> "$out"
      added+=("$1")
    fi
  }
  # Make sure the file ends with a newline before appending.
  [[ -z "$(tail -c 1 "$out")" ]] || echo >> "$out"
  # Valkey (the Redis-compatible store) requires a password since 0.0.1-beta.
  add_key REDIS_PASSWORD "$(token 40)"
  add_key MAIL_STARTTLS true
  add_key MAIL_SMTP_AUTH true
  add_key ACME_DIRECTORY_URL https://acme-v02.api.letsencrypt.org/directory
  add_key ACME_ACCOUNT_EMAIL ""
  add_key ACME_EAB_KEY_ID ""
  add_key ACME_EAB_HMAC_KEY ""
  if [[ ${#added[@]} -eq 0 ]]; then
    echo "$out already has every key this release needs; nothing changed."
  else
    echo "Added to $out: ${added[*]}"
    echo "Next: docker compose up -d"
  fi
  exit 0
fi

if [[ -e "$out" ]]; then
  echo "$out already exists. Delete it only if you also want to start from an empty database." >&2
  echo "To add keys a newer release needs (for example REDIS_PASSWORD), run: ./setup.sh --upgrade" >&2
  exit 1
fi

domain="${1:-localhost}"
if [[ ! "$domain" =~ ^[A-Za-z0-9.-]+$ ]]; then
  echo "Give a plain DNS name, for example certping.example.com" >&2
  exit 2
fi

if [[ "$domain" == "localhost" ]]; then
  url="http://localhost"
  site=":80"
else
  url="https://${domain}"
  site="${domain}"
fi

jwt_lines="$("$here/../../apps/server/scripts/jwt-keygen.sh" "selfhosted-$(date +%Y%m%d)" "$url")"
admin_domain="$domain"; [[ "$domain" == "localhost" ]] && admin_domain="certping.local"
admin_password="$(token 20)-9aA"

umask 077
cat > "$out" <<ENV
# Generated by setup.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Keep this file private and backed up.

# Where people and remote agents reach CertPing.
CERTPING_URL='${url}'
CERTPING_SITE_ADDRESS='${site}'

# The first Platform Super Admin, created by the server at its first start with this random
# password; you choose a new one at the first sign-in. Empty all three to use the setup screen
# in the web app instead.
BOOTSTRAP_SUPER_ADMIN_USERNAME='admin'
BOOTSTRAP_SUPER_ADMIN_EMAIL='admin@${admin_domain}'
BOOTSTRAP_SUPER_ADMIN_PASSWORD='${admin_password}'
BOOTSTRAP_SUPER_ADMIN_DISPLAY_NAME='Administrator'

DB_USERNAME='certping'
DB_PASSWORD='$(token 32)'

# Valkey, the Redis-compatible store (revoked tokens and feature flags), requires this password;
# the server sends it.
REDIS_PASSWORD='$(token 40)'

# Encrypts password hashes at rest.
PASSWORD_PEPPER_ACTIVE_VERSION='v1'
PASSWORD_PEPPER_V1='$(rand 32)'
PASSWORD_RESET_TOKEN_SECRET='$(token 48)'

# Agent gateway. The notifier reads notifications with the internal token; the bundled agent
# connects with the bootstrap token once the first organization exists.
CERTPING_INTERNAL_TOKEN='$(token 48)'
CERTPING_BOOTSTRAP_AGENT_TOKEN='cpa_$(token 43)'
CERTPING_BOOTSTRAP_AGENT_ORG=''

# Encrypts the private keys and credentials the server and the bundled agent share on disk.
CERTPING_LOCAL_SECRET_KEY='$(rand 32)'

# Let's Encrypt (or any ACME CA). The address gets the CA's expiry and policy notices.
ACME_ACCOUNT_EMAIL=''
ACME_DIRECTORY_URL='https://acme-v02.api.letsencrypt.org/directory'

# For a CA that requires external account binding (ZeroSSL, Google Trust Services, SSL.com): the
# key id and HMAC key it issues. Leave both empty for Let's Encrypt.
ACME_EAB_KEY_ID=''
ACME_EAB_HMAC_KEY=''

# Extra CA certificates the server, notifier and agent trust (a private ACME CA such as step-ca,
# a TLS-inspecting proxy, an internal SMTP relay): a PEM file on this machine, for example
# CERTPING_EXTRA_CA_CERTS='/etc/certping/corp-ca.pem'

# Single sign-on with your OpenID Connect provider (optional). Sign-in stays local only until all
# four are set. Register ${url}/login/oauth2/code/sso as the redirect URI at the provider;
# CERTPING_OIDC_ORGANIZATION is the slug or id of the organization members sign into.
CERTPING_OIDC_ISSUER_URI=''
CERTPING_OIDC_CLIENT_ID=''
CERTPING_OIDC_CLIENT_SECRET=''
CERTPING_OIDC_ORGANIZATION=''
CERTPING_OIDC_DISPLAY_NAME='Single sign-on'

# Opt-in usage report to the CertPing project (counts and versions only, docs/self-hosting.md#privacy-and-telemetry).
CERTPING_TELEMETRY_ENABLED='false'

# Outgoing email (optional until you want notifications). Any SMTP server works.
MAIL_HOST=''
MAIL_PORT='587'
MAIL_USERNAME=''
MAIL_PASSWORD=''
EMAIL_FROM='certping@${domain}'
# Set both to 'false' for an internal relay that has no TLS or sign-in.
MAIL_STARTTLS='true'
MAIL_SMTP_AUTH='true'

${jwt_lines}
ENV

echo "Wrote $out for ${url}"
echo
echo "Next:"
echo "  docker compose up -d"
echo "  open ${url} and sign in as admin (you will choose a new password)"
echo
echo "  Username: admin"
echo "  Password: not printed. Read it from the file, which only you can open:"
echo "    grep '^BOOTSTRAP_SUPER_ADMIN_PASSWORD=' $out"
