package com.certmanagement.interceptor;

import com.certmanagement.security.ClientAddressResolver;
import com.certmanagement.security.GatewayRequestContext;
import com.certmanagement.util.MdcIds;
import com.certmanagement.util.OtelSpanContext;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.ObjectMapper;
import tools.jackson.databind.json.JsonMapper;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;
import org.slf4j.MDC;
import org.springframework.stereotype.Component;
import org.springframework.web.servlet.HandlerInterceptor;

import java.nio.charset.StandardCharsets;
import java.util.UUID;

/**
 * Interceptor to extract and store request context (requestId, correlationId, idempotencyKey)
 * from HTTP headers, query parameters, or JSON request body.
 * The ids live in the SLF4J MDC only, so the log pattern, {@code RequestContextLogger} and anything
 * {@code MdcContextPropagator} hands to a worker read the same values.
 *
 * <p>Extraction priority for each field:
 * <ul>
 *   <li><b>requestId</b>: GatewayRequestContext (JWT-generated) → X-Request-ID header → requestId query param</li>
 *   <li><b>correlationId</b>: X-Correlation-ID header → correlationId query param → JSON body "correlationId" field</li>
 *   <li><b>idempotencyKey</b>: X-Idempotency-Key header</li>
 * </ul>
 *
 * <p>Body extraction requires the request to be wrapped by {@link RequestBodyCachingFilter}
 * (which caches JSON request bodies for re-reading).</p>
 */
@Component
public class RequestContextInterceptor implements HandlerInterceptor {

    private static final String IDEMPOTENCY_KEY = "idempotencyKey";
    // Not an id and never logged, so it stays out of the MDC and off worker threads.
    private static final ThreadLocal<String> CLIENT_IP_HOLDER = new ThreadLocal<>();
    private static final ObjectMapper OBJECT_MAPPER = JsonMapper.builderWithJackson2Defaults().build();

    private final ClientAddressResolver clientAddressResolver;

    public RequestContextInterceptor(ClientAddressResolver clientAddressResolver) {
        this.clientAddressResolver = clientAddressResolver;
    }

    @Override
    public boolean preHandle(HttpServletRequest request, HttpServletResponse response, Object handler) throws Exception {
        // requestId: prefer the ID generated by JwtAuthenticationFilter in GatewayRequestContext,
        // fall back to header/param (for non-JWT endpoints or testing)
        String requestId = null;
        if (GatewayRequestContext.isPresent() && GatewayRequestContext.getRequestId() != null) {
            requestId = GatewayRequestContext.getRequestId();
        } else {
            requestId = extractValue(request, "X-Request-ID", "requestId");
        }

        // correlationId: header → query param → JSON body
        String correlationId = extractValue(request, "X-Correlation-ID", "correlationId");
        if (correlationId == null) {
            correlationId = extractFieldFromBody(request, "correlationId");
        }

        String idempotencyKey = request.getHeader("X-Idempotency-Key");

        // Mint requestId AND correlationId when they're missing — covers anonymous endpoints
        // (login, forgot-password, OAuth init/callback) where JwtAuthenticationFilter
        // doesn't run to populate GatewayRequestContext, and the client (Postman / curl /
        // browser) often doesn't send X-Request-ID or X-Correlation-ID either.
        //
        // The "-http-" prefix distinguishes interceptor-minted ids from:
        //   * JwtAuthenticationFilter's "req-<nanoTime>" (authenticated-request mint)
        //   * frontend-supplied values (no prefix; whatever shape they choose)
        //
        // Both ids flow through MDC → agent commands → agent → response handler → auto-deploy
        // fan-out, so every log line and audit row for the request can be grepped by a
        // single `req=` / `corr=` value.
        boolean requestIdMinted     = (requestId == null);
        boolean correlationIdMinted = (correlationId == null);
        String resolvedRequestId     = requestIdMinted     ? "req-http-"  + UUID.randomUUID() : requestId;
        String resolvedCorrelationId = correlationIdMinted ? "corr-http-" + UUID.randomUUID() : correlationId;

        CLIENT_IP_HOLDER.set(clientAddressResolver.resolve(request));
        if (idempotencyKey != null && !idempotencyKey.isEmpty()) {
            MDC.put(IDEMPOTENCY_KEY, idempotencyKey);
        }

        // Every log line emitted on this request thread carries [reqId corrId orgId] via the
        // logging.pattern template — including stack traces.
        MDC.put("requestId", resolvedRequestId);
        MDC.put("correlationId", resolvedCorrelationId);
        // organizationId comes from the JWT (decoded by JwtAuthenticationFilter). It's not on
        // the request body or headers we trust — never accept it from client input.
        String organizationId = null;
        if (GatewayRequestContext.isPresent()) {
            organizationId = GatewayRequestContext.getOrganizationId();
            if (organizationId != null && !organizationId.isEmpty()) {
                MDC.put("organizationId", organizationId);
            }
        }

        String userId = GatewayRequestContext.isPresent() && GatewayRequestContext.getUserId() != null
                ? String.valueOf(GatewayRequestContext.getUserId())
                : null;
        OtelSpanContext.enrichHttp(resolvedRequestId, resolvedCorrelationId, organizationId, userId);

        // Echo the resolved requestId on the response so the frontend (and any intermediary
        // logging proxy) can correlate without needing to inspect the request log. The agent's
        // TraceMdcFilter does the same — keeps cross-service symmetry.
        response.setHeader("X-Request-ID", resolvedRequestId);

        // Also store correlationId in GatewayRequestContext so ProxyService can forward it
        // downstream. Use resolvedCorrelationId (not the original `correlationId` from input)
        // so the server-minted id propagates too — otherwise downstream services would see
        // no correlationId for any request that arrived without an X-Correlation-ID header.
        if (GatewayRequestContext.isPresent()) {
            GatewayRequestContext.setCorrelationId(resolvedCorrelationId);
        }

        return true;
    }

    @Override
    public void afterCompletion(HttpServletRequest request, HttpServletResponse response, Object handler, Exception ex) throws Exception {
        // The next request on this pooled thread must not inherit stale ids.
        clearContext();
    }

    private String extractValue(HttpServletRequest request, String headerName, String paramName) {
        String value = request.getHeader(headerName);
        if (value != null && !value.isEmpty()) {
            return value;
        }
        value = request.getParameter(paramName);
        if (value != null && !value.isEmpty()) {
            return value;
        }
        return null;
    }

    /**
     * Extract a field value from the cached JSON request body.
     * Reads from the request attribute set by {@link RequestBodyCachingFilter}.
     * This works regardless of how many times the request has been wrapped
     * (e.g. by Spring Security's FirewalledRequest).
     */
    private String extractFieldFromBody(HttpServletRequest request, String fieldName) {
        Object attr = request.getAttribute(RequestBodyCachingFilter.CACHED_BODY_ATTR);
        if (!(attr instanceof byte[] body) || body.length == 0) {
            return null;
        }
        try {
            JsonNode root = OBJECT_MAPPER.readTree(new String(body, StandardCharsets.UTF_8));
            JsonNode node = root.get(fieldName);
            if (node != null && !node.isNull() && node.isString()) {
                String value = node.asString();
                return value.isEmpty() ? null : value;
            }
            return null;
        } catch (Exception e) {
            // Best-effort — body may not be valid JSON (e.g. form data)
            return null;
        }
    }

    public static String getCurrentRequestId() {
        // Not MdcIds.requestId(): that mints an orphan id where callers expect "unknown".
        String requestId = MDC.get("requestId");
        return requestId != null ? requestId : "unknown";
    }

    public static String getCurrentCorrelationId() {
        String correlationId = MdcIds.correlationId();
        return correlationId != null ? correlationId : "unknown";
    }

    /**
     * The caller's IP address for this request as {@link ClientAddressResolver} decided it, or null when
     * none could be read. Audit rows ({@code AuditContext}) read it here.
     */
    public static String getCurrentClientIp() {
        return CLIENT_IP_HOLDER.get();
    }

    public static String getCurrentIdempotencyKey() {
        String idempotencyKey = MDC.get(IDEMPOTENCY_KEY);
        return idempotencyKey != null ? idempotencyKey : "none";
    }

    public static void setCurrentRequestId(String requestId) {
        putOrRemove("requestId", requestId);
    }

    public static void setCurrentCorrelationId(String correlationId) {
        putOrRemove("correlationId", correlationId);
    }

    public static void setCurrentClientIp(String clientIp) {
        CLIENT_IP_HOLDER.set(clientIp);
    }

    public static void setCurrentIdempotencyKey(String idempotencyKey) {
        putOrRemove(IDEMPOTENCY_KEY, idempotencyKey);
    }

    public static void clearContext() {
        CLIENT_IP_HOLDER.remove();
        MDC.remove("requestId");
        MDC.remove("correlationId");
        MDC.remove(IDEMPOTENCY_KEY);
        MDC.remove("messageId");
        MDC.remove("organizationId");
    }

    private static void putOrRemove(String key, String value) {
        if (value == null) {
            MDC.remove(key);
        } else {
            MDC.put(key, value);
        }
    }

    public static String getFormattedContext() {
        String requestId = getCurrentRequestId();
        String correlationId = getCurrentCorrelationId();
        String idempotencyKey = getCurrentIdempotencyKey();

        StringBuilder context = new StringBuilder();
        context.append("requestId=").append(requestId);
        context.append(", correlationId=").append(correlationId);
        if (!"none".equals(idempotencyKey)) {
            context.append(", idempotencyKey=").append(idempotencyKey);
        }
        return context.toString();
    }
}
